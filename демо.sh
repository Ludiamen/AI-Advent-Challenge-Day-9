#!/usr/bin/env bash
# Практическая проверка из задания Дня 8: как растут токены и стоимость по ходу
# диалога и что ломается при переполнении контекста.
#
# Имена переменных латиницей: bash не поддерживает кириллицу в идентификаторах
# и молча превращает $ИМЯ в обычный текст.
#
# Запуск:  bash демо.sh  [путь-к-python]
set -u
PY="${1:-.venv/bin/python}"
DB="демо.db"

step() { printf '\n\n=== %s ===\n' "$1"; }

rm -f "$DB"

step "1. КОРОТКИЙ ДИАЛОГ: из чего складывается запрос"
"$PY" cli.py --база "$DB" --сессия диалог --токены \
  "Назови одним предложением, что такое нематериальный актив."

step "2. ВТОРОЙ ХОД: в запрос добавилась история"
"$PY" cli.py --база "$DB" --сессия диалог --токены \
  "А чем он отличается от расходов периода?" 2>&1 | tail -13

step "3. ДЛИННЫЙ ДИАЛОГ: ещё шесть обменов подряд"
# Сбои не прячем: на бесплатном тарифе тут легко упереться в лимит
# «токенов в минуту», и это часть наблюдаемой картины.
for q in \
  "Что такое стоимостной лимит НМА?" \
  "Как определить срок полезного использования?" \
  "Что делать с бессрочной лицензией?" \
  "Чем SaaS отличается от коробочного ПО в учёте?" \
  "Как учитывать доработку купленного ПО?" \
  "Нужно ли проверять НМА на обесценение?"
do
  if "$PY" cli.py --база "$DB" --сессия диалог "$q" > /dev/null 2>/tmp/день8.err; then
    printf '.'
  else
    printf '\n  сбой на вопросе «%s»:\n  ' "$q"
    head -c 200 /tmp/день8.err
    printf '\n'
  fi
done
printf ' готово\n'
"$PY" cli.py --база "$DB" --сессия диалог --рост

step "4. ПЕРЕПОЛНЕНИЕ, режим «обрезать» (по умолчанию)"
"$PY" cli.py --база "$DB" --сессия диалог --окно 1200 --логи \
  "Повтори, о чём мы говорили в самом начале." 2>&1 \
  | grep -E "Контекст переполнен|из истории взято|Расход" | head -3

step "5. ПЕРЕПОЛНЕНИЕ, режим «отказать»"
"$PY" cli.py --база "$DB" --сессия диалог --окно 1200 --при-переполнении отказать \
  "Повтори, о чём мы говорили в самом начале." 2>&1 | tail -2

step "6. ЧТО ЛОМАЕТСЯ БЕЗ ЗАЩИТЫ: запрос уходит как есть"
LOAD=$("$PY" нагрузка.py 6000 --модель groq-allam7b)
"$PY" cli.py --база "$DB" --сессия переполнение --модель groq-allam7b \
  --при-переполнении отправить --токены "$LOAD" 2>&1 \
  | grep -E "итого запрос|контекст |Ошибка" | head -4

step "7. ТА ЖЕ РАБОТА НА ПЛАТНОЙ МОДЕЛИ: во что обходятся токены"
"$PY" cli.py --база "$DB" --сессия платная --модель ds-flash --токены \
  "Назови одним предложением, что такое нематериальный актив." 2>&1 | tail -3
"$PY" cli.py --база "$DB" --сессия платная --модель ds-flash --токены \
  "А чем он отличается от расходов периода?" 2>&1 | tail -2

step "8. ИТОГ ПО СЕССИЯМ"
"$PY" cli.py --база "$DB" --сессии

printf '\nБаза: %s\n' "$DB"
