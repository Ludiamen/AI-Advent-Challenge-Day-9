"""Сжатие истории диалога: давние реплики заменяются краткой выжимкой.

Зачем. Каждая реплика отправляется модели вместе со всей прошлой перепиской,
поэтому запрос дорожает линейно с длиной разговора — в Day-8 замерено, что за
восемь обменов входная часть выросла в 19,5 раза. Рано или поздно это упирается
и в деньги, и в контекстное окно, и в лимит токенов в минуту.

Идея. Последние несколько обменов нужны дословно: в них уточнения, местоимения,
«а если наоборот». Всё, что старше, можно свернуть в несколько предложений —
кто собеседник, о чём договорились, какие числа назывались. Выжимка занимает
десятки токенов вместо тысяч, а разговор продолжается связно.

Как устроено здесь. Выжимка накатывается: новая делается из предыдущей плюс
реплик, состарившихся с прошлого раза. Это дёшево и работает при любой длине
разговора, но детали от поколения к поколению размываются — эффект испорченного
телефона. Поэтому сырые сообщения из базы не удаляются никогда: выжимку всегда
можно пересобрать заново командой, а сам разговор — прочитать целиком.

Делает выжимку отдельная дешёвая модель: работа механическая, сильная модель
здесь не нужна, а на платной основной модели сжатие съедало бы часть экономии.

Публичное API:
  SUMMARY_SYSTEM / build_summary_prompt() — промпты для модели-сжимателя
  render_summary(text)                    — как выжимка подставляется в запрос
  DEFAULT_*                               — настройки по умолчанию
"""

from __future__ import annotations

# Модель по умолчанию для сжатия: бесплатная и быстрая.
DEFAULT_SUMMARIZER = "groq-20b"

# Сколько последних сообщений всегда остаются дословными.
DEFAULT_KEEP_LAST = 6

# Сколько состарившихся сообщений должно накопиться, чтобы запустить сжатие.
DEFAULT_COMPRESS_EVERY = 10

# Доля доступного контекста, после которой сжатие запускается досрочно,
# не дожидаясь нужного числа сообщений.
DEFAULT_THRESHOLD = 0.5

# Предел длины самой выжимки — иначе она сама разрастётся до размеров истории.
DEFAULT_SUMMARY_TOKENS = 400

SUMMARY_SYSTEM = """\
Ты ведёшь конспект делового разговора между пользователем и агентом-бухгалтером,
который разбирает ИТ-расходы по ФСБУ 14/2022.

Твоя работа — сжать разговор так, чтобы по конспекту можно было продолжить его
без потери сути. Пиши по-русски, сухо и плотно, без вступлений и оценок.

ГЛАВНОЕ ПРАВИЛО: то, что сообщил ПОЛЬЗОВАТЕЛЬ, важнее того, что ответил агент.
Сведения пользователя переноси полностью и дословно в части чисел и названий.
Ответы агента сжимай до вывода в одну строку — подробные разъяснения, проводки
и цитаты из стандарта не переписывай, их всегда можно получить заново.

ОБЯЗАТЕЛЬНО СОХРАНИ:
  * кто собеседник, его роль, организацию и любые названные им данные;
  * ВСЕ числа и идентификаторы, названные пользователем: суммы, сроки, лимиты,
    ставки, ИНН, номера счетов и договоров, даты. Ни одного не пропусти;
  * названия документов и объектов учёта, которые обсуждались;
  * решения и выводы, к которым пришли, — по одной строке на каждый;
  * вопросы, оставшиеся без ответа.

МОЖНО ОПУСТИТЬ:
  * приветствия, благодарности и вежливые обороты;
  * повторы и переформулировки одного и того же;
  * развёрнутые разъяснения агента, таблицы и примеры проводок;
  * цитаты из стандарта — достаточно ссылки на пункт.

Начни с раздела «Факты от пользователя» — перечисли их списком, ничего не
пропустив. Затем раздел «Обсуждено» — по строке на каждый вывод.

Отвечай только текстом конспекта, без заголовков и пояснений о том, что это
конспект."""

_ПРЕДЫДУЩАЯ = """\
Ниже конспект более раннего отрезка того же разговора. Включи его содержание в
новый конспект, ничего не потеряв из чисел и договорённостей.

=== КОНСПЕКТ ПРЕДЫДУЩЕГО ОТРЕЗКА ===
{summary}
"""

_ПРОДОЛЖЕНИЕ = """\
=== НОВЫЙ ОТРЕЗОК РАЗГОВОРА ===
{dialogue}

Составь единый конспект, укладывающийся примерно в {limit} токенов."""

# Как выжимка выглядит в запросе к основной модели. Помечена явно: модель должна
# понимать, что это пересказ прошлого, а не чья-то реплика.
SUMMARY_TEMPLATE = """\
Краткое содержание более раннего отрезка этого же разговора (пересказ, не дословно):

{summary}

Далее идут последние сообщения дословно."""


def render_dialogue(messages: list[dict]) -> str:
    """Разворачивает сообщения в читаемый текст для модели-сжимателя."""
    строки = []
    for сообщение in messages:
        кто = "Пользователь" if сообщение.get("role") == "user" else "Агент"
        текст = (сообщение.get("content") or "").strip()
        if текст:
            строки.append(f"{кто}: {текст}")
    return "\n\n".join(строки)


def build_summary_prompt(
    messages: list[dict],
    previous: str = "",
    limit: int = DEFAULT_SUMMARY_TOKENS,
) -> str:
    """Собирает запрос к модели-сжимателю: прошлый конспект плюс новые реплики."""
    части = []
    if previous.strip():
        части.append(_ПРЕДЫДУЩАЯ.format(summary=previous.strip()))
    части.append(_ПРОДОЛЖЕНИЕ.format(dialogue=render_dialogue(messages), limit=limit))
    return "\n".join(части)


def render_summary(summary: str) -> str:
    """Оформляет выжимку так, как она подставляется в запрос вместо истории."""
    return SUMMARY_TEMPLATE.format(summary=summary.strip())
