@dataclass
class Прогон:
    """Результаты одного сценария — со сжатием или без."""

    название: str
    сжатие: bool
    обмены: list[dict] = field(default_factory=list)
    ответ_на_проверку: str = ""
    вспомнено: list[str] = field(default_factory=list)
    забыто: list[str] = field(default_factory=list)
    сжатий: int = 0
    токены_сжатия: int = 0
    стоимость_сжатия: float = 0.0
    ошибки: list[str] = field(default_factory=list)

    @property
    def входные(self) -> int:
        return sum(о["prompt_tokens"] for о in self.обмены)

    @property
    def выходные(self) -> int:
        return sum(о["completion_tokens"] for о in self.обмены)

    @property
    def всего(self) -> int:
        return self.входные + self.выходные + self.токены_сжатия

    @property
    def стоимость(self) -> float:
        return sum(о["cost"] for о in self.обмены) + self.стоимость_сжатия

    @property
    def последний_запрос(self) -> int:
        return self.обмены[-1]["prompt_tokens"] if self.обмены else 0

    @property
    def первый_запрос(self) -> int:
        return self.обмены[0]["prompt_tokens"] if self.обмены else 0

    @property
    def точность(self) -> float:
        всего = len(self.вспомнено) + len(self.забыто)
        return len(self.вспомнено) / всего if всего else 0.0


def проверить_факты(ответ: str) -> tuple[list[str], list[str]]:
    """Ищет в ответе каждый из исходных фактов."""
    вспомнено, забыто = [], []
    for название, _значение, образец in ФАКТЫ:
        (вспомнено if re.search(образец, ответ, re.IGNORECASE) else забыто).append(название)
    return вспомнено, забыто


def прогнать(
    название: str,
    сжатие: bool,
    реплики: list[str],
    база: str,
    модель: str,
    сжиматель: str,
    keep_last: int,
    every: int,
    пауза: float,
    остывание: float,
) -> Прогон:
    """Проводит один сценарий целиком и собирает замеры."""
    итог = Прогон(название=название, сжатие=сжатие)
    агент = DocumentAnalysisAgent(
        model_key=модель, memory=база, session=название, compress=сжатие,
        summarizer_model=сжиматель, keep_last=keep_last, compress_every=every,
        chat_prompt=КРАТКИЙ_ПРОМПТ,
    )
    агент.clear_history()

    for номер, реплика in enumerate(реплики, start=1):
        try:
            агент.ask(реплика)
        except AgentError as exc:
            итог.ошибки.append(f"реплика {номер}: {exc}")
            print(f"  ⚠ реплика {номер}: {str(exc)[:120]}")
            continue

        расход = агент.last_usage
        итог.обмены.append({
            "номер": номер,
            "prompt_tokens": расход.get("prompt_tokens", 0),
            "completion_tokens": расход.get("completion_tokens", 0),
            "cost": расход.get("cost", 0.0),
        })
        сжато = агент.last_compression
        if сжато.get("compressed"):
            итог.сжатий += 1
            итог.токены_сжатия += сжато.get("spent_tokens", 0)
            итог.стоимость_сжатия += сжато.get("spent_cost", 0.0)
            агент.last_compression = {}
        print(f"  {номер:>2}. запрос {расход.get('prompt_tokens', 0):>5} токенов"
              + ("  ← сжатие" if сжато.get("compressed") else ""))
        time.sleep(пауза)

    # Перед проверочным вопросом даём минутному лимиту расхода восстановиться.
    # Без этого он приходится ровно на исчерпанный бюджет, ответ не приходит, и
    # замер памяти оказывается пустым — не потому, что агент забыл, а потому,
    # что его не спросили.
    if остывание > 0:
        print(f"  … пауза {остывание:.0f} с перед проверочным вопросом")
        time.sleep(остывание)

    try:
        итог.ответ_на_проверку = агент.ask(ПРОВЕРОЧНЫЙ)
        расход = агент.last_usage
        итог.обмены.append({
            "номер": len(реплики) + 1,
            "prompt_tokens": расход.get("prompt_tokens", 0),
            "completion_tokens": расход.get("completion_tokens", 0),
            "cost": расход.get("cost", 0.0),
        })
    except AgentError as exc:
        итог.ошибки.append(f"проверочный вопрос: {exc}")
        print(f"  ⚠ проверочный вопрос: {str(exc)[:120]}")

    итог.вспомнено, итог.забыто = проверить_факты(итог.ответ_на_проверку)
    return итог


def замер_состоялся(прогон: Прогон) -> bool:
    """Есть ли ответ на проверочный вопрос: без него о памяти судить нельзя."""
    return bool(прогон.ответ_на_проверку.strip())


def напечатать(без: Прогон, со: Прогон) -> None:
    """Выводит сравнение двух прогонов."""
    линия = "-" * 78
    print("\n" + "=" * 78)
    print("СРАВНЕНИЕ: без сжатия и со сжатием")
    print("=" * 78)
    print(f"{'показатель':<34} {'без сжатия':>14} {'со сжатием':>14} {'разница':>12}")
    print(линия)

    def строка(имя, а, б, форматтер=lambda x: tokens.format_tokens(int(x)), лучше_меньше=True):
        if а:
            доля = (б - а) / а * 100
            разница = f"{доля:+.0f}%"
        else:
            разница = "—"
        print(f"{имя:<34} {форматтер(а):>14} {форматтер(б):>14} {разница:>12}")

    строка("входных токенов всего", без.входные, со.входные)
    строка("выходных токенов всего", без.выходные, со.выходные)
    строка("токенов на сжатие", без.токены_сжатия, со.токены_сжатия)
    строка("токенов итого", без.всего, со.всего)
    строка("первый запрос", без.первый_запрос, со.первый_запрос)
    строка("последний запрос", без.последний_запрос, со.последний_запрос)
    print(f"{'стоимость':<34} {tokens.format_cost(без.стоимость):>14} "
          f"{tokens.format_cost(со.стоимость):>14}")
    print(f"{'сжатий выполнено':<34} {без.сжатий:>14} {со.сжатий:>14}")
    print(линия)
    if not (замер_состоялся(без) and замер_состоялся(со)):
        print("Проверка памяти не состоялась: ответ на проверочный вопрос не получен.")
        print("Сравнивать качество не по чему — увеличьте --остывание и повторите.")
        return
    print(f"{'фактов вспомнено':<34} "
          f"{f'{len(без.вспомнено)} из {len(ФАКТЫ)}':>14} "
          f"{f'{len(со.вспомнено)} из {len(ФАКТЫ)}':>14}")
    if без.забыто:
        print(f"  без сжатия потеряно: {', '.join(без.забыто)}")
    if со.забыто:
        print(f"  со сжатием потеряно: {', '.join(со.забыто)}")
    print()

    if со.всего < без.всего:
        экономия = (без.всего - со.всего) / без.всего
        print(f"Сжатие сэкономило {экономия:.0%} токенов "
              f"({tokens.format_tokens(без.всего - со.всего)}).")
    else:
        перерасход = (со.всего - без.всего) / без.всего if без.всего else 0
        print(f"Сжатие НЕ окупилось: расход вырос на {перерасход:.0%}. "
              f"На коротком разговоре выжимка стоит дороже, чем экономит.")

    if со.точность < без.точность:
        print(f"Ценой стала память: со сжатием потеряно фактов "
              f"{len(со.забыто)}, без сжатия — {len(без.забыто)}.")
    elif со.точность == без.точность:
        print("Качество не пострадало: оба варианта вспомнили одинаково.")


def выводы(без: Прогон, со: Прогон) -> list[str]:
    """Формулирует итог по числам, а не по впечатлению."""
    строки: list[str] = []

    экономия_входа = (без.входные - со.входные) / без.входные if без.входные else 0
    строки.append(
        f"- **Входная часть запроса** уменьшилась на {экономия_входа:.0%} "
        f"({tokens.format_tokens(без.входные)} → "
        f"{tokens.format_tokens(со.входные)} токенов). Это и есть прямое действие "
        f"сжатия: в запрос уходит выжимка вместо давних реплик."
    )

    разница = (со.всего - без.всего) / без.всего if без.всего else 0
    if со.всего < без.всего:
        строки.append(
            f"- **Итоговый расход** ниже на {-разница:.0%}: экономия на запросах "
            f"перекрыла {tokens.format_tokens(со.токены_сжатия)} токенов, "
            f"потраченных на сами выжимки."
        )
    else:
        строки.append(
            f"- **Итоговый расход выше на {разница:.0%}**: сами выжимки обошлись в "
            f"{tokens.format_tokens(со.токены_сжатия)} токенов и на разговоре такой "
            f"длины не окупились. Сжатие начинает экономить там, где история "
            f"успевает вырасти настолько, что перевешивает стоимость конспекта."
        )

    if без.последний_запрос:
        доля = (без.последний_запрос - со.последний_запрос) / без.последний_запрос
        строки.append(
            f"- **Последний запрос** меньше на {доля:.0%} "
            f"({tokens.format_tokens(без.последний_запрос)} → "
            f"{tokens.format_tokens(со.последний_запрос)}). Именно этот показатель "
            f"решает, упрётся ли разговор в контекстное окно и в минутный лимит "
            f"расхода: там важен размер одного запроса, а не сумма за сессию."
        )

    if замер_состоялся(без) and замер_состоялся(со):
        if len(со.вспомнено) > len(без.вспомнено):
            строки.append(
                f"- **Качество выросло, а не упало.** Без сжатия агент вспомнил "
                f"{len(без.вспомнено)} факта из {len(ФАКТЫ)}, со сжатием — "
                f"{len(со.вспомнено)}. Без сжатия давние реплики просто не помещаются "
                f"в отправляемую историю и пропадают молча; выжимка же удерживает их "
                f"в сжатом виде. Потеряно без сжатия: {', '.join(без.забыто)}."
            )
        elif len(со.вспомнено) == len(без.вспомнено):
            строки.append(
                f"- **Качество не изменилось:** оба варианта вспомнили по "
                f"{len(со.вспомнено)} факта из {len(ФАКТЫ)}."
            )
        else:
            строки.append(
                f"- **Качество упало:** со сжатием вспомнено {len(со.вспомнено)} "
                f"из {len(ФАКТЫ)} против {len(без.вспомнено)} без него. "
                f"Потеряно: {', '.join(со.забыто)}."
            )
        if со.забыто:
            строки.append(
                f"- Со сжатием всё же потеряно: {', '.join(со.забыто)}. Выжимка — "
                f"пересказ, и мелкие идентификаторы в нём выживают хуже всего."
            )

    return строки


def markdown(без: Прогон, со: Прогон, модель: str, сжиматель: str, реплик: int) -> str:
    """Собирает отчёт о сравнении."""
    строки = [
        "# Day-9 — сжатие истории: что оно даёт и чего стоит",
        "",
        f"Один и тот же сценарий из {реплик} реплик прогнан дважды: без сжатия и со "
        f"сжатием. Основная модель — `{catalog.get(модель).api_id}`, выжимку делает "
        f"`{catalog.get(сжиматель).api_id}`.",
        "",
        "Расход взят из поля `usage` ответов API — это факт, а не оценка. Качество "
        "меряется проверкой на память: в начале разговора пользователь называет восемь "
        "конкретных сведений, в конце агента просят их повторить, и ответ проверяется "
        "на наличие каждого значения.",
        "",
        "## Расход",
        "",
        "| Показатель | Без сжатия | Со сжатием | Разница |",
        "|------------|------------|------------|---------|",
    ]

    def строка(имя, а, б):
        разница = f"{(б - а) / а * 100:+.0f}%" if а else "—"
        строки.append(f"| {имя} | {tokens.format_tokens(int(а))} | "
                      f"{tokens.format_tokens(int(б))} | {разница} |")

    строка("Входных токенов", без.входные, со.входные)
    строка("Выходных токенов", без.выходные, со.выходные)
    строка("Токенов на сжатие", без.токены_сжатия, со.токены_сжатия)
    строка("**Итого токенов**", без.всего, со.всего)
    строка("Первый запрос", без.первый_запрос, со.первый_запрос)
    строка("Последний запрос", без.последний_запрос, со.последний_запрос)
    строки.append(f"| Стоимость | {tokens.format_cost(без.стоимость)} | "
                  f"{tokens.format_cost(со.стоимость)} | |")
    строки.append(f"| Сжатий выполнено | {без.сжатий} | {со.сжатий} | |")

    строки += [
        "",
        "## Качество: сохранились ли исходные сведения",
        "",
        "| Сведение | Значение | Без сжатия | Со сжатием |",
        "|----------|----------|------------|------------|",
    ]
    for название, значение, _ in ФАКТЫ:
        строки.append(
            f"| {название} | {значение} | "
            f"{'✅' if название in без.вспомнено else '❌'} | "
            f"{'✅' if название in со.вспомнено else '❌'} |"
        )
    строки.append(f"| **Итого** | | **{len(без.вспомнено)} из {len(ФАКТЫ)}** | "
                  f"**{len(со.вспомнено)} из {len(ФАКТЫ)}** |")

    строки += ["", "## Как рос запрос", "",
               "| Обмен | Без сжатия | Со сжатием |", "|-------|------------|------------|"]
    for i in range(max(len(без.обмены), len(со.обмены))):
        а = tokens.format_tokens(без.обмены[i]["prompt_tokens"]) if i < len(без.обмены) else "—"
        б = tokens.format_tokens(со.обмены[i]["prompt_tokens"]) if i < len(со.обмены) else "—"
        строки.append(f"| {i + 1} | {а} | {б} |")

    итог = выводы(без, со)
    if итог:
        строки += ["", "## Выводы", ""] + итог

    строки += ["", "## Ответы на проверочный вопрос", ""]
    for прогон in (без, со):
        строки += [f"### {прогон.название}", "", "```text", прогон.ответ_на_проверку.strip(), "```", ""]

    if без.ошибки or со.ошибки:
        строки += ["## Сбои во время прогона", ""]
        for прогон in (без, со):
            for ошибка in прогон.ошибки:
                строки.append(f"- **{прогон.название}**: {ошибка}")
        строки.append("")

    return "\n".join(строки) + "\n"


def main() -> int:
    """Точка входа: прогоняет сценарий дважды и сводит результаты."""
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--реплик", dest="turns", type=int, default=10, metavar="N",
                        help="сколько реплик в сценарии (по умолчанию 10)")
    parser.add_argument("--модель", dest="model", default=catalog.DEFAULT_MODEL,
                        metavar="КЛЮЧ", help="основная модель диалога")
    parser.add_argument("--сжиматель", dest="summarizer", default="groq-20b",
                        metavar="КЛЮЧ", help="модель, делающая выжимку")
    parser.add_argument("--дословно", dest="keep_last", type=int, default=4, metavar="N",
                        help="сколько последних сообщений не сжимать")
    parser.add_argument("--каждые", dest="every", type=int, default=6, metavar="N",
                        help="через сколько состарившихся сообщений сжимать")
    parser.add_argument("--пауза", type=float, default=4.0, metavar="СЕК",
                        help="пауза между репликами: бережёт минутный лимит расхода")
    parser.add_argument("--остывание", type=float, default=70.0, metavar="СЕК",
                        help="пауза перед проверочным вопросом, чтобы лимит расхода "
                             "восстановился и ответ точно пришёл")
    parser.add_argument("--база", default="", metavar="ПУТЬ",
                        help="файл базы (по умолчанию временный)")
    parser.add_argument("--md", default="", metavar="ФАЙЛ", help="сохранить отчёт")
    args = parser.parse_args()

    if args.turns < len(ВВОДНЫЕ) + 1:
        print(f"Реплик должно быть хотя бы {len(ВВОДНЫЕ) + 1}: "
              f"первые {len(ВВОДНЫЕ)} задают факты.", file=sys.stderr)
        return 1

    реплики = ВВОДНЫЕ + НАПОЛНЕНИЕ[: args.turns - len(ВВОДНЫЕ)]
    база = args.база or os.path.join(tempfile.gettempdir(), "сравнение-день9.db")

    print(f"Сценарий: {len(реплики)} реплик, затем проверочный вопрос.")
    print(f"Модель: {catalog.get(args.model).api_id}, "
          f"сжиматель: {catalog.get(args.summarizer).api_id}, "
          f"дословно последних: {args.keep_last}, сжатие каждые {args.every}.\n")

    try:
        print("── БЕЗ СЖАТИЯ " + "─" * 50)
        без = прогнать("без-сжатия", False, реплики, база, args.model,
                       args.summarizer, args.keep_last, args.every,
                       args.пауза, args.остывание)
        print(f"\n… пауза {args.остывание:.0f} с между прогонами")
        time.sleep(args.остывание)
        print("── СО СЖАТИЕМ " + "─" * 50)
        со = прогнать("со-сжатием", True, реплики, база, args.model,
                      args.summarizer, args.keep_last, args.every,
                      args.пауза, args.остывание)
    except (AgentError, KeyError) as exc:
        print(f"Ошибка: {exc}", file=sys.stderr)
        return 1

    напечатать(без, со)

    if args.md:
        with open(args.md, "w", encoding="utf-8") as файл:
            файл.write(markdown(без, со, args.model, args.summarizer, len(реплики)))
        print(f"\nОтчёт сохранён: {args.md}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
