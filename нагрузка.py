#!/usr/bin/env python3
"""Генератор текста заданного объёма — нужен, чтобы упереться в лимит контекста.

Заполнить контекст осмысленным разговором дорого и долго, а увидеть переполнение
надо. Скрипт печатает текст примерно на N токенов из словаря предметной области.

Слова берутся вразнобой с фиксированным зерном: повторяющийся текст токенизатор
сжимает заметно лучше, и на нём переполнение наступает позже, чем на обычном.
Зерно фиксировано, чтобы прогоны были воспроизводимыми.

Запуск:
    python нагрузка.py 3000            # текст примерно на 3000 токенов
    python нагрузка.py 3000 --модель groq-allam7b   # с учётом её токенизатора
"""

import argparse
import random
import sys

from agent import catalog, tokens

СЛОВАРЬ = (
    "лицензия договор актив амортизация стоимость реестр организация признание "
    "выгода контроль носитель программа сервер подписка отчётность стандарт "
    "норматив бухгалтер учёт списание баланс период критерий срок исключительный "
    "неисключительный правообладатель вознаграждение спецификация приложение"
).split()

SEED = 7


def сгенерировать(целевые_токены: int, model_key: str = "") -> str:
    """Подбирает длину текста так, чтобы оценка вышла около целевого значения."""
    множитель = 1.0
    if model_key:
        множитель = catalog.get(model_key).token_factor

    случайный = random.Random(SEED)
    слова: list[str] = []
    while True:
        слова.extend(случайный.choice(СЛОВАРЬ) for _ in range(50))
        текст = " ".join(слова)
        if round(tokens.estimate(текст) * множитель) >= целевые_токены:
            return текст


def main() -> int:
    """Точка входа: печатает текст запрошенного объёма в стандартный вывод."""
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("токенов", type=int, help="желаемый объём текста в токенах")
    parser.add_argument("--модель", dest="model", default="", metavar="КЛЮЧ",
                        help="учесть токенизатор конкретной модели из каталога")
    args = parser.parse_args()

    if args.токенов < 1:
        print("Объём должен быть положительным.", file=sys.stderr)
        return 1
    print(сгенерировать(args.токенов, args.model))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
