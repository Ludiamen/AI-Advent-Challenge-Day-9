def тесты_бюджета_агента(каталог: str) -> None:
    print("\nБюджет контекста и переполнение (agent):")

    def отвечает(запрос: httpx.Request) -> httpx.Response:
        return httpx.Response(200, json={
            "model": "тестовая", "choices": [{"message": {"content": "Ответ"}}],
            "usage": {"prompt_tokens": 300, "completion_tokens": 100},
        })

    агент = агент_с_транспортом(отвечает)
    б = агент.budget("Короткий вопрос")
    проверить("системный промпт учтён", б.system > 0)
    равно("истории пока нет", б.history, 0)
    проверить("вопрос учтён", б.question > 0)
    проверить("обёртка провайдера учтена", б.overhead > 0)
    равно("окно взято из каталога", б.limit, catalog.get(агент.model_key).context_window)

    агент.ask("Первый вопрос")
    проверить("после обмена история занимает место", агент.budget("Ещё вопрос").history > 0)

    # Токенизаторы разные: тот же текст у allam-2-7b дороже, чем у gpt-oss.
    текст = "Нематериальный актив признаётся при выполнении пяти условий."
    дешёвая = агент_с_транспортом(отвечает, model_key="groq-120b").estimate(текст)
    дорогая = агент_с_транспортом(отвечает, model_key="groq-allam7b").estimate(текст)
    проверить("у allam-2-7b тот же текст дороже", дорогая > дешёвая * 2,
              f"{дорогая} против {дешёвая}")

    # Резерв под ответ не съедает весь контекст маленькой модели.
    малая = агент_с_транспортом(отвечает, model_key="groq-allam7b")
    равно("резерв ограничен половиной окна", малая.reserve, малая.context_window // 2)
    проверить("под запрос остаётся место", малая.budget("вопрос").free > 0)

    # Искусственно узкое окно — так переполнение проверяется без больших трат.
    узкая = агент_с_транспортом(отвечает, context_limit=500)
    равно("окно можно уменьшить", узкая.context_window, 500)
    проверить("настоящее окно модели больше",
              узкая.info()["real_context_window"] > 500)

    # Режим «отказать»: агент останавливается и называет числа.
    отказ = агент_с_транспортом(отвечает, context_limit=400, on_overflow="отказать")
    for i in range(6):
        try:
            отказ.ask(f"Вопрос номер {i} с некоторым количеством слов для объёма")
        except AgentError:
            break
    проверить("режим «отказать» останавливает разговор",
              поймать(lambda: отказ.ask("Ещё один вопрос"), "не помещается"))
    проверить("  и объясняет, что делать",
              поймать(lambda: отказ.ask("Ещё один вопрос"), "обрезать"))

    # Режим «обрезать»: разговор продолжается, но история усечена.
    отправленные: list[dict] = []

    def запомнить(запрос: httpx.Request) -> httpx.Response:
        отправленные.append(json.loads(запрос.content))
        return отвечает(запрос)

    # compress=False намеренно: здесь проверяется именно обрезка истории,
    # а сжатие подменило бы её другим механизмом.
    обрезка = агент_с_транспортом(запомнить, context_limit=700, on_overflow="обрезать",
                                  compress=False,
                                  memory=os.path.join(каталог, "обрезка.db"))
    for i in range(6):
        обрезка.ask(f"Вопрос {i}: " + "слово " * 30)
    последний = отправленные[-1]["messages"]
    проверить("режим «обрезать» доводит разговор до конца", len(отправленные) == 6)
    проверить("  но история усечена", len(последний) < 2 + 2 * 5,
              f"сообщений в запросе: {len(последний)}")
    равно("  первое сообщение — системное", последний[0]["role"], "system")
    if len(последний) > 1:
        равно("  дальше идёт реплика пользователя", последний[1]["role"], "user")
    обрезка.memory.close()

    # Слишком большой запрос не спасает даже пустая история.
    громадный = агент_с_транспортом(отвечает, context_limit=200)
    проверить("непомещающийся вопрос отвергается с объяснением",
              поймать(lambda: громадный.ask("слово " * 500), "даже без истории"))

    # Режим «отправить»: агент не вмешивается, ошибку возвращает провайдер.
    def лимит(запрос: httpx.Request) -> httpx.Response:
        return httpx.Response(400, json={"error": {"message": "Please reduce the length"}})

    насквозь = агент_с_транспортом(лимит, context_limit=200, on_overflow="отправить")
    проверить("режим «отправить» доносит ошибку провайдера",
              поймать(lambda: насквозь.ask("слово " * 500), "400"))

    проверить("неизвестный режим переполнения отвергается",
              поймать_создание(on_overflow="как-нибудь"))


