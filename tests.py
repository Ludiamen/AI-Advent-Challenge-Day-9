def тесты_анализа(каталог: str) -> None:
    print("\nРазбор документа целиком (analyze):")

    путь = os.path.join(каталог, "договор.docx")
    документ = Document()
    документ.add_paragraph("Лицензия на СУБД, 850 000 руб., срок 36 месяцев.")
    документ.save(путь)

    def отвечает(запрос: httpx.Request) -> httpx.Response:
        # Модель отвечает в markdown-ограждении, как это часто бывает на практике.
        return ответ_модели("```json\n" + json.dumps(ОТВЕТ_МОДЕЛИ, ensure_ascii=False) + "\n```")

    агент = агент_с_транспортом(отвечает)
    результат = агент.analyze(путь)

    равно("объектов разобрано", len(результат["items"]), 2)
    равно("тип документа взят из ответа", результат["document_info"]["document_type"], "договор")
    равно("имя файла подставлено", результат["document_info"]["source_file"], "договор.docx")
    равно("первый объект — НМА", результат["items"][0]["category"], fsbu.NMA)
    равно("второй объект — SaaS", результат["items"][1]["category"], fsbu.SAAS)
    равно("сводка по сумме", результат["summary"]["total_cost"], 970_000.0)
    равно("сводка по количеству", результат["summary"]["total_items"], 2)
    равно("ошибок разбора нет", результат["meta"]["parse_error"], "")

    # Ответ не в JSON: агент обязан не упасть, а честно отдать сырой текст.
    агент = агент_с_транспортом(lambda з: ответ_модели("Не смог разобрать документ."))
    сырой = агент.analyze(путь)
    равно("ответ не в JSON — объектов нет", сырой["items"], [])
    проверить("  и объяснено, почему", "JSON" in сырой["meta"]["parse_error"])

    агент = агент_с_транспортом(lambda з: ответ_модели('{"document_type": "договор", "items": []}'))
    пусто = агент.analyze(путь)
    проверить("пустой список объектов объяснён", "ни одного объекта" in пусто["meta"]["parse_error"])

    агент = агент_с_транспортом(отвечает)
    проверить("несуществующий файл — понятная ошибка",
              поймать(lambda: агент.analyze(os.path.join(каталог, "нет.docx")), "не найден"))

    текстовый = os.path.join(каталог, "заметка.txt")
    open(текстовый, "w", encoding="utf-8").write("текст")
    проверить("неподдерживаемый формат — понятная ошибка",
              поймать(lambda: агент.analyze(текстовый), "Неподдерживаемый формат"))

    старый = os.path.join(каталог, "договор.doc")
    open(старый, "w", encoding="utf-8").write("текст")
    проверить("формат .doc отклоняется с подсказкой",
              поймать(lambda: агент.analyze(старый), "пересохраните"))

    равно("analyze_text работает без файла",
          len(агент_с_транспортом(отвечает).analyze_text("Лицензия на 850 000")["items"]), 2)
    проверить("пустой текст не уходит в сеть",
              поймать(lambda: агент_с_транспортом(отвечает).analyze_text("  "), "Пустой текст"))


