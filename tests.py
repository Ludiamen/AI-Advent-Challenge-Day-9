#!/usr/bin/env python3
"""Тесты агента — без единого обращения к LLM и без сети.

Запуск:
    python tests.py

Что проверяется и почему именно это:

  * правила ФСБУ (fsbu.py) — это ядро, которому агент доверяет вместо модели,
    поэтому категории, лимит и амортизация проверены на всех четырёх исходах;
  * разбор ответа модели — она присылает числа строками, «да» вместо true и
    заворачивает JSON в markdown, хотя её просили этого не делать;
  * слой HTTP — поднят на httpx.MockTransport: настоящих запросов нет, но
    проверены успех, повтор после сбоя, отказ по ключу и пустой ответ;
  * чтение документов — на файлах, которые тест создаёт сам;
  * отчёт Excel — книга собирается и тут же читается обратно;
  * инкапсуляция — интерфейсы не должны знать про LLM;
  * память — главное требование этого дня: история переживает остановку
    процесса, поэтому персистентность проверяется буквально, на файле базы,
    который переоткрывают заново;
  * каталог моделей — переключение не должно рвать разговор;
  * подсчёт токенов — оценка до запроса, факт после, накопление по сессии
    и поведение при переполнении контекста;
  * сжатие истории — главное этого дня: когда запускается, что попадает в
    выжимку, а главное — что ничего не теряется по дороге.
"""

