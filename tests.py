# --- 11. Страница веб-интерфейса ---------------------------------------------


def тесты_страницы() -> None:
    """Статическая проверка шаблона страницы.

    Повод завести эту группу был конкретный: в скрипте страницы одно и то же имя
    было занято дважды — элементом <input type=file> и функцией. Для браузера это
    синтаксическая ошибка, из-за которой не выполняется ВЕСЬ скрипт: переставали
    работать и перетаскивание файла, и выбор по клику, и сама отправка вопроса.
    Ни один серверный тест такого не ловит — страница отдаётся с кодом 200, а
    ломается уже у пользователя.
    """
    print("\nСтраница веб-интерфейса (templates/index.html):")

    корень = os.path.dirname(os.path.abspath(__file__))
    html = open(os.path.join(корень, "templates", "index.html"), encoding="utf-8").read()

    найден = re.search(r"<script>(.*?)</script>", html, re.DOTALL)
    проверить("в шаблоне есть скрипт", найден is not None)
    if найден is None:
        return
    скрипт = найден.group(1)

    # Каждый элемент, который скрипт ищет по id, должен быть в разметке.
    for идентификатор in sorted(set(re.findall(r"getElementById\('([^']+)'\)", скрипт))):
        проверить(
            f"элемент с id={идентификатор} есть в разметке",
            f'id="{идентификатор}"' in html,
        )

    # Разметка зоны загрузки: без скрытого поля файла выбор по клику невозможен.
    проверить("зона перетаскивания на месте", 'id="зона"' in html)
    проверить("скрытое поле выбора файла на месте", 'type="file"' in html)
    проверить("поле ограничивает форматы", 'accept=".pdf,.docx,.xlsx"' in html)
    for событие in ("dragenter", "dragover", "dragleave", "drop"):
        проверить(f"обработчик события {событие} назначен", f"'{событие}'" in скрипт)
    проверить("клик по зоне открывает выбор файла", "выбор.click()" in скрипт)

    # Синтаксис скрипта проверяем настоящим движком JavaScript, если он есть.
    node = shutil.which("node")
    if node is None:
        print("  ПРОПУСК синтаксис скрипта — node не установлен")
        return

    with tempfile.NamedTemporaryFile("w", suffix=".js", encoding="utf-8", delete=False) as файл:
        файл.write(скрипт)
        путь = файл.name
    try:
        готово = subprocess.run(
            [node, "--check", путь], capture_output=True, text=True, timeout=30
        )
        проверить(
            "скрипт страницы разбирается без синтаксических ошибок",
            готово.returncode == 0,
            готово.stderr.strip()[:300],
        )
    finally:
        os.unlink(путь)



