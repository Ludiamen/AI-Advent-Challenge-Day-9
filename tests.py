# --- 3. Слой HTTP на поддельном транспорте -----------------------------------


def агент_с_транспортом(обработчик, **поля) -> DocumentAnalysisAgent:
    """Агент, у которого HTTP-клиент отвечает заранее заданной функцией.

    Память по умолчанию держится в оперативке: тесты не должны трогать
    настоящий файл истории на диске.
    """
    поля.setdefault("memory", ":memory:")
    клиент = httpx.Client(transport=httpx.MockTransport(обработчик))
    return DocumentAnalysisAgent(api_key="test-key-123", http_client=клиент, **поля)


def ответ_модели(текст: str) -> httpx.Response:
    return httpx.Response(200, json={
        "model": "тестовая-модель",
        "choices": [{"message": {"content": текст}}],
        "usage": {"prompt_tokens": 10, "completion_tokens": 20},
    })


def тесты_http() -> None:
    print("\nСлой HTTP (httpx.MockTransport, сети нет):")

    запросы: list[httpx.Request] = []

    def успех(запрос: httpx.Request) -> httpx.Response:
        запросы.append(запрос)
        return ответ_модели("Ответ агента")

    агент = агент_с_транспортом(успех)
    равно("ask возвращает текст ответа", агент.ask("вопрос"), "Ответ агента")
    равно("  запрос ушёл ровно один", len(запросы), 1)

    тело = json.loads(запросы[0].content)
    равно("  адрес запроса", str(запросы[0].url).endswith("/chat/completions"), True)
    равно("  ключ ушёл в заголовке",
          запросы[0].headers["authorization"], "Bearer test-key-123")
    равно("  два сообщения: system и user", len(тело["messages"]), 2)
    равно("  температура передана", тело["temperature"], 0.2)
    проверить("  для свободного вопроса берётся чат-промпт",
              "помощник бухгалтера" in тело["messages"][0]["content"])
    равно("  расход токенов сохранён", агент.last_usage["completion_tokens"], 20)

    попытки = {"n": 0}

    def сбой_потом_успех(запрос: httpx.Request) -> httpx.Response:
        попытки["n"] += 1
        if попытки["n"] == 1:
            return httpx.Response(500, text="временная ошибка сервера")
        return ответ_модели("Получилось со второй попытки")

    агент = агент_с_транспортом(сбой_потом_успех)
    равно("после ошибки 500 делается повтор",
          агент.ask("вопрос"), "Получилось со второй попытки")
    равно("  попыток было две", попытки["n"], 2)

    агент = агент_с_транспортом(lambda з: httpx.Response(401, text="unauthorized"))
    проверить("отказ по ключу — понятная ошибка",
              поймать(lambda: агент.ask("вопрос"), "отклонил ключ"))

    агент = агент_с_транспортом(lambda з: httpx.Response(500, text="всё плохо"))
    проверить("постоянная ошибка сервера — ошибка агента",
              поймать(lambda: агент.ask("вопрос"), "Не удалось получить ответ"))

    агент = агент_с_транспортом(lambda з: ответ_модели(""))
    проверить("пустой ответ модели — ошибка агента",
              поймать(lambda: агент.ask("вопрос"), "пустой ответ"))

    агент = агент_с_транспортом(lambda з: httpx.Response(200, text="не json"))
    проверить("неожиданный формат ответа — ошибка агента",
              поймать(lambda: агент.ask("вопрос"), "Неожиданный формат"))

    кириллица = DocumentAnalysisAgent(api_key="ключ-с-кириллицей", memory=":memory:")
    проверить("ключ с кириллицей отвергается понятной ошибкой",
              поймать(lambda: кириллица.ask("вопрос"), "недопустимые символы"))

    без_ключа = DocumentAnalysisAgent(api_key="", memory=":memory:")
    равно("без ключа агент не готов", без_ключа.ready, False)
    проверить("  и говорит, что делать", поймать(lambda: без_ключа.ask("вопрос"), "ключ API"))

    проверить("пустой вопрос не уходит в сеть",
              поймать(lambda: агент_с_транспортом(успех).ask("   "), "Пустой запрос"))

    # DeepSeek: температура действует только при отключённом размышлении (вывод Day-4).
    тела: list[dict] = []

    def запомнить(запрос: httpx.Request) -> httpx.Response:
        тела.append(json.loads(запрос.content))
        return ответ_модели("ок")

    агент_deepseek = агент_с_транспортом(запомнить, model_key="ds-flash")
    агент_deepseek.ask("вопрос")
    равно("для DeepSeek размышление отключается",
          тела[0].get("thinking"), {"type": "disabled"})

    тела.clear()
    агент_с_транспортом(запомнить).ask("вопрос")
    проверить("для других провайдеров поле thinking не шлётся", "thinking" not in тела[0])


def поймать(действие, фрагмент: str) -> bool:
    """Проверяет, что действие бросает AgentError с нужным фрагментом текста."""
    try:
        действие()
    except AgentError as exc:
        return фрагмент.lower() in str(exc).lower()
    return False


