def тесты_токенов() -> None:
    print("\nПодсчёт токенов (tokens.py):")

    равно("пустой текст — ноль токенов", tokens_module.estimate(""), 0)
    проверить("любой непустой текст — хотя бы один токен",
              tokens_module.estimate("а") >= 1)
    проверить("длинный текст дороже короткого",
              tokens_module.estimate("слово " * 50) > tokens_module.estimate("слово"))

    классы = tokens_module.classify("Привет, world 42!")
    равно("кириллица посчитана", классы["кириллица"], 6)
    равно("латиница посчитана", классы["латиница"], 5)
    равно("цифры посчитаны", классы["цифры"], 2)
    равно("сумма классов равна длине текста",
          sum(классы.values()), len("Привет, world 42!"))

    # Цифры и знаки дороже букв — это видно и на глаз, и в коэффициентах.
    проверить("цифры дороже букв той же длины",
              tokens_module.estimate("1234567890") > tokens_module.estimate("абвгдеёжзи"))

    сообщения = [{"role": "user", "content": "привет"}, {"role": "assistant", "content": "и вам"}]
    проверить("оценка списка сообщений учитывает обёртку",
              tokens_module.estimate_messages(сообщения)
              > tokens_module.estimate("привет") + tokens_module.estimate("и вам"))
    равно("пустой список — ноль", tokens_module.estimate_messages([]), 0)

    равно("стоимость миллиона входных токенов",
          round(tokens_module.cost(1_000_000, 0, 0.44, 1.32), 6), 0.44)
    равно("стоимость миллиона выходных",
          round(tokens_module.cost(0, 1_000_000, 0.44, 1.32), 6), 1.32)
    равно("бесплатная модель ничего не стоит",
          tokens_module.cost(10_000, 10_000, 0.0, 0.0), 0.0)

    равно("разряды разделяются", tokens_module.format_tokens(12345), "12 345")
    равно("нулевая стоимость подписывается словом",
          tokens_module.format_cost(0), "бесплатно")
    проверить("мелкая сумма не округляется в ноль",
              tokens_module.format_cost(0.000173) != "0.0000 $")

    # Бюджет: из чего складывается запрос и когда он перестаёт помещаться.
    б = tokens_module.Budget(limit=1000, reserved=200, system=100, history=300,
                             question=50, overhead=10)
    равно("запрос — сумма частей", б.prompt, 460)
    равно("доступно = окно минус резерв", б.available, 800)
    равно("запас = доступно минус запрос", б.free, 340)
    равно("переполнения нет", б.overflow, False)
    проверить("описание содержит числа", "460" in б.describe().replace(" ", "").replace(" ", ""))

    тесно = tokens_module.Budget(limit=1000, reserved=900, system=100, history=300,
                                 question=50, overhead=10)
    равно("переполнение распознано", тесно.overflow, True)
    проверить("запас отрицательный", тесно.free < 0)
