ВСЕ_КРИТЕРИИ = {name: True for name in CRITERIA_FIELDS}
ПРОВАЛЫ: list[str] = []


def проверить(название: str, условие: bool, подробности: str = "") -> None:
    """Регистрирует один результат и печатает его."""
    if условие:
        print(f"  OK   {название}")
    else:
        ПРОВАЛЫ.append(название)
        print(f"  ПРОВАЛ {название}" + (f"\n         {подробности}" if подробности else ""))


def равно(название: str, получено, ожидалось) -> None:
    проверить(название, получено == ожидалось, f"ожидали {ожидалось!r}, получили {получено!r}")


def предмет(**поля) -> Item:
    """Объект учёта с выполненными критериями, если не сказано иное."""
    поля.setdefault("position", "Тестовый объект")
    поля.setdefault("criteria", dict(ВСЕ_КРИТЕРИИ))
    поля.setdefault("term_type", "fixed")
    return Item(**поля)


