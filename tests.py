def не_начинается_с_ответа(срез: list[dict]) -> bool:
    return not срез or срез[0]["role"] == "user"


def поймать_память(действие, фрагмент: str) -> bool:
    try:
        действие()
    except memory_module.MemoryError as exc:
        return фрагмент.lower() in str(exc).lower()
    return False


