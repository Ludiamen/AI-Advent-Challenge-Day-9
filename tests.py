def тесты_сжатия_память() -> None:
    print("\nХранение выжимок (memory.py):")

    хранилище = ConversationMemory(":memory:")
    for i in range(6):
        хранилище.append_pair("с", f"вопрос {i}", f"ответ {i}")

    равно("всего сообщений", len(хранилище.messages("с")), 12)
    равно("выжимки пока нет", хранилище.latest_summary("с"), None)

    ожидают = хранилище.pending("с", keep_last=4)
    равно("под сжатие идёт всё, кроме последних четырёх", len(ожидают), 8)
    равно("  начиная с самого давнего", ожидают[0]["content"], "вопрос 0")

    хранилище.save_summary("с", "Обсудили вопросы 0-3.", covers_until=ожидают[-1]["id"],
                           messages=8, model="сжиматель", tokens=120)
    выжимка = хранилище.latest_summary("с")
    равно("выжимка сохранена", выжимка["content"], "Обсудили вопросы 0-3.")
    равно("  поколение первое", выжимка["generation"], 1)
    равно("  запомнено, сколько свёрнуто", выжимка["messages"], 8)
    равно("после сжатия ждать больше нечего", хранилище.pending("с", 4), [])

    хранилище.save_summary("с", "Второй конспект.", covers_until=выжимка["covers_until"],
                           messages=8)
    равно("поколения нумеруются", хранилище.latest_summary("с")["generation"], 2)
    равно("прежние поколения сохраняются", len(хранилище.summaries("с")), 2)

    сводка = хранилище.stats("с")
    равно("выжимки посчитаны в сводке", сводка["summaries"], 2)
    равно("  и их расход", сводка["summary_tokens"], 120)

    # Регрессия: сообщения между границей выжимки и последними keep_last
    # обязаны уходить в запрос. Когда-то они выпадали — сжаты ещё не были,
    # а в контекст уже не попадали, и агент терял названные пользователем факты.
    свежее = ConversationMemory(":memory:")
    for i in range(5):
        свежее.append_pair("g", f"вопрос {i}", f"ответ {i}")
    первые = свежее.pending("g", keep_last=4)
    свежее.save_summary("g", "Свёрнуто начало.", covers_until=первые[-1]["id"],
                        messages=len(первые))
    свежее.append_pair("g", "новый вопрос", "новый ответ")

    отправляемые = свежее.after_summary("g")
    тексты = [м["content"] for м in отправляемые]
    проверить("сообщения после выжимки не теряются", "новый вопрос" in тексты)
    проверить("  и промежуточные тоже", "вопрос 4" in тексты,
              f"в запрос ушло: {тексты}")
    равно("  первым идёт пользователь", отправляемые[0]["role"], "user")

    # Очистка убирает и выжимки: конспект без разговора бессмыслен.
    свежее.clear("g")
    равно("после очистки выжимок нет", свежее.latest_summary("g"), None)

    # А пересборка стирает только конспект, оставляя разговор.
    хранилище.drop_summaries("с")
    равно("выжимки удалены", хранилище.latest_summary("с"), None)
    равно("  а сообщения на месте", len(хранилище.messages("с")), 12)


def тесты_сжатия_агент(каталог: str) -> None:
    print("\nСжатие в агенте (agent.compress):")

    агент = агент_с_транспортом(выжималка(), keep_last=2, compress_every=4)
    # Порог считается по состарившимся сообщениям: keep_last=2 оставляет
    # дословными последнюю пару, значит четыре штуки накопятся к четвёртой
    # реплике — тогда сжатие и запустится.
    for i in range(4):
        агент.ask(f"вопрос {i}")

    выжимка = агент.summary()
    проверить("сжатие сработало само", выжимка is not None)
    if выжимка:
        равно("  выжимка сохранена", выжимка["content"], "Конспект разговора.")

    итог = агент.last_compression
    проверить("отчёт о сжатии заполнен", итог.get("compressed", 0) > 0)
    проверить("  видно, сколько было", итог.get("tokens_before", 0) > 0)
    проверить("  и сколько стало", итог.get("tokens_after", 0) > 0)
    проверить("  и во что обошлось само сжатие", итог.get("spent_tokens", 0) > 0)
    равно("  обрыва не было", итог.get("truncated"), False)

    контекст = агент._history_for_model()
    равно("выжимка идёт первой", контекст[0]["role"], "system")
    проверить("  и помечена как пересказ", "пересказ" in контекст[0]["content"])
    проверить("  дальше идут дословные реплики", len(контекст) > 1)

    # Выключенное сжатие возвращает поведение прежних дней.
    без = агент_с_транспортом(выжималка(), compress=False)
    for i in range(6):
        без.ask(f"вопрос {i}")
    равно("без сжатия выжимка не создаётся", без.summary(), None)
    проверить("  и в контексте нет системных вставок",
              all(м["role"] != "system" for м in без._history_for_model()))

    # Сжатие ходит к отдельной модели, основная не меняется.
    запросы: list[dict] = []

    def запомнить(запрос: httpx.Request) -> httpx.Response:
        запросы.append(json.loads(запрос.content))
        return выжималка()(запрос)

    отдельная = агент_с_транспортом(запомнить, keep_last=2, compress_every=4,
                                    model_key="groq-120b", summarizer_model="groq-20b")
    for i in range(4):
        отдельная.ask(f"вопрос {i}")
    модели = {т["model"] for т in запросы}
    проверить("запросы уходили двум моделям", len(модели) == 2, f"модели: {модели}")
    равно("основная модель не сменилась", отдельная.model_key, "groq-120b")
    сжимающие = [т for т in запросы if т["model"] == catalog.get("groq-20b").api_id]
    проверить("сжатие просит неглубокое рассуждение",
              any(т.get("reasoning_effort") == "low" for т in сжимающие))

    # Принудительное сжатие и пересборка.
    ручное = агент_с_транспортом(выжималка("Ручной конспект."), keep_last=2,
                                 compress_every=100)
    for i in range(4):
        ручное.ask(f"вопрос {i}")
    равно("по порогу сжатия не было", ручное.summary(), None)
    итог = ручное.compress(force=True)
    проверить("принудительное сжатие сработало", итог["compressed"] > 0)
    равно("  выжимка появилась", ручное.summary()["content"], "Ручной конспект.")

    пересборка = ручное.rebuild_summary()
    проверить("пересборка выполнена", пересборка["compressed"] > 0)
    равно("  и поколение снова первое", ручное.summary()["generation"], 1)
    равно("  сырые сообщения целы", len(ручное.history()), 8)

    равно("сжимать нечего — так и сказано",
          агент_с_транспортом(выжималка()).compress(force=True)["compressed"], 0)

    # Сбой сжатия не должен ронять разговор.
    состояние = {"первый": True}

    def ломается(запрос: httpx.Request) -> httpx.Response:
        тело = json.loads(запрос.content)
        if тело["model"] == catalog.get("groq-20b").api_id:
            return httpx.Response(500, text="сжиматель недоступен")
        return выжималка()(запрос)

    стойкий = агент_с_транспортом(ломается, keep_last=2, compress_every=4,
                                  summarizer_model="groq-20b")
    for i in range(4):
        стойкий.ask(f"вопрос {i}")
    равно("разговор продолжился без выжимки", len(стойкий.history()), 8)
    равно("  выжимки нет", стойкий.summary(), None)
    проверить("  но сбой зафиксирован", "error" in стойкий.last_compression)

    # Неизвестная модель-сжиматель отвергается при создании.
    проверить("несуществующий сжиматель отвергается",
              поймать_создание(summarizer_model="нет-такой"))

    # Сведения о сжатии видны интерфейсам.
    сведения = агент.info()
    равно("состояние сжатия в info", сведения["compress"], True)
    проверить("  указана модель-сжиматель", bool(сведения["summarizer"]))
    проверить("  и текст выжимки", bool(сведения["summary"]))
    проверить("  info по-прежнему не раскрывает промпты",
              "chat_prompt" not in сведения)


